public class Variables {
    public static void main(String[] args){

        // Premitive Variables
        int rollNumber = 12;
        int houseNumber = 101;
        
        double gpa = 1.2;
        double carMileage = 34.5;

        char grade = 'A';
        char currency = '$';
        
        boolean forSale = true;
        boolean isStudent = false;

        // Reference Variables
        String name = "Unish";
        String email = "fake123@gmail.com";
        // we can add a numbers but it is treated as a char rather than an int

        
    }
}
